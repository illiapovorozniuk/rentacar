            singleMode: false,
            format: 'DD MMMM YYYY',
            autoApply: true,
            inlineMode: true,
            lang: '{{$locale}}',
            minDate: tomorrow,
            lockDays: disabledDates,
            setup: (picker) => {
                picker.on('selected', (startDate, endDate) => {
                    const start = new Date(startDate.dateInstance -1);
                    const end = new Date(endDate.dateInstance -1);

                    const range = getDateRangeArray(
                        new Date(start.setDate(start.getDate() + 1)),
                        new Date(end.setDate(end.getDate() + 1))
                    );

                    const hasDisabled = range.some(date => disabledSet.has(date));
                    if (hasDisabled) {
                        picker.clearSelection();
                        console.log('Selected date range includes disabled dates. Please choose another range.');
                        document.getElementById('car_price').innerText = '';
                    } else {
                        // Якщо все ок — встановлюємо приховані поля
                        document.getElementById('date_from').value = formatDate(start);
                        document.getElementById('date_to').value = formatDate(end);
                        // Розрахунок ціни
                        const days = range.length;
                        let total = 0;
                        if (days >= 30) {
                            total = days * price_30;
                        } else if (days >= 7) {
                            total = days * price_7;
                        } else {
                            total = days * price_1;
                        }
                        // Додаємо доставку, якщо хоча б одне поле адреси заповнене
                        const pickup = document.getElementById('pickup_address').value.trim();
                        const dropoff = document.getElementById('dropoff_address').value.trim();
                        if (pickup || dropoff) {
                            total += delivery;
                        }
                        document.getElementById('car_price').innerText = Math.round(total) + ' ' + currencySign;
                    }
                });
            }
        });

        // Додаємо слухачі на зміну адрес
        ['pickup_address', 'dropoff_address'].forEach(id => {
            document.getElementById(id).addEventListener('input', function() {
                if (picker.getStartDate() && picker.getEndDate()) {
                    picker.emit('selected', picker.getStartDate(), picker.getEndDate());
                }
            });
        });

        // AJAX submit for order form
        document.querySelector('form').addEventListener('submit', function(e) {
            e.preventDefault();
            const form = this;
            const formData = new FormData(form);
            formData.append('currency', '{{ $current_currency->slug }}');
            fetch(form.action || window.location.href, {
                method: 'POST',
                headers: {
                    'X-Requested-With': 'XMLHttpRequest',
                    'X-CSRF-TOKEN': document.querySelector('input[name="_token"]').value
                },
                body: formData
            })
            .then(response => response.json())
            .then(data => {
                if (data.redirect_url) {
                    window.location.href = data.redirect_url;
                }
            })
            .catch(error => {
                console.log('Error: ' + error.message);
            });
        });
    </script>
